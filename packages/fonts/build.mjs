// Copy the latin subset of each curated font out of node_modules into files/,
// and write the manifest. The result is COMMITTED: the app must not depend on
// a node_modules tree at runtime (a packaged desktop app has none), and every
// font here is OFL or Apache licensed, so redistributing the files is fine.
//
//   npm run build -w @knitted/fonts

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const nm = join(here, "../../node_modules");
mkdirSync(join(here, "files"), { recursive: true });

// [family, package, file stem, category, kind, weights]
const FONTS = [
  ["Bricolage Grotesque", "@fontsource-variable/bricolage-grotesque", "bricolage-grotesque", "display", "variable", [200, 800]],
  ["Geist", "@fontsource-variable/geist", "geist", "sans", "variable", [100, 900]],
  ["Geist Mono", "@fontsource-variable/geist-mono", "geist-mono", "mono", "variable", [100, 900]],
  ["Instrument Serif", "@fontsource/instrument-serif", "instrument-serif", "serif", "static-italic", [400, 400]],
  ["Inter", "@fontsource-variable/inter", "inter", "sans", "variable", [100, 900]],
  ["DM Sans", "@fontsource-variable/dm-sans", "dm-sans", "sans", "variable", [100, 1000]],
  ["Space Grotesk", "@fontsource-variable/space-grotesk", "space-grotesk", "display", "variable", [300, 700]],
  ["Outfit", "@fontsource-variable/outfit", "outfit", "display", "variable", [100, 900]],
  ["Plus Jakarta Sans", "@fontsource-variable/plus-jakarta-sans", "plus-jakarta-sans", "sans", "variable", [200, 800]],
  ["Sora", "@fontsource-variable/sora", "sora", "display", "variable", [100, 800]],
  ["Manrope", "@fontsource-variable/manrope", "manrope", "sans", "variable", [200, 800]],
  ["Archivo", "@fontsource-variable/archivo", "archivo", "sans", "variable", [100, 900]],
  ["Playfair Display", "@fontsource-variable/playfair-display", "playfair-display", "serif", "variable", [400, 900]],
  ["Fraunces", "@fontsource-variable/fraunces", "fraunces", "serif", "variable", [100, 900]],
  ["Lora", "@fontsource-variable/lora", "lora", "serif", "variable", [400, 700]],
  ["DM Serif Display", "@fontsource/dm-serif-display", "dm-serif-display", "serif", "static", [400, 400]],
  ["Bebas Neue", "@fontsource/bebas-neue", "bebas-neue", "display", "static", [400, 400]],
  ["JetBrains Mono", "@fontsource-variable/jetbrains-mono", "jetbrains-mono", "mono", "variable", [100, 800]],
];

const manifest = [];
for (const [family, pkg, stem, category, kind, [wmin, wmax]] of FONTS) {
  const names = kind === "variable" ? [`${stem}-latin-wght-normal.woff2`] : kind === "static-italic" ? [`${stem}-latin-400-italic.woff2`] : [`${stem}-latin-400-normal.woff2`];
  const src = join(nm, pkg, "files", names[0]);
  if (!existsSync(src)) throw new Error(`${family}: ${src} is missing. Is ${pkg} installed?`);
  copyFileSync(src, join(here, "files", names[0]));
  const lic = readFileSync(join(nm, pkg, "LICENSE"), "utf8").split("\n")[0].trim();
  manifest.push({ family, category, file: names[0], style: kind === "static-italic" ? "italic" : "normal", weight: [wmin, wmax], license: /apache/i.test(lic) ? "Apache-2.0" : "OFL-1.1" });
}
writeFileSync(join(here, "src/manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`${manifest.length} fonts, ${manifest.reduce((n, f) => n + readFileSync(join(here, "files", f.file)).length, 0) / 1024 | 0} KB`);

// The same list, for the browser: a plain array the font picker can import
// without pulling Node into the client bundle.
writeFileSync(join(here, "../../apps/studio/lib/editor/fonts.ts"),
  `// GENERATED by packages/fonts/build.mjs. Do not edit.\n// The bundled families, as a plain list for the font picker, kept as data so the\n// browser bundle stays free of Node.\nexport const manifestFamilies = ${JSON.stringify(manifest.map((f) => f.family), null, 2)};\n`);
